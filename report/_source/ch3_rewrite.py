def set_runs(p, parts):
    runs = p._p.findall('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}r')
    proto = copy.deepcopy(runs[0])
    for r in runs:
        p._p.remove(r)
    for part in parts:
        text, sty = (part if isinstance(part, tuple) else (part, {}))
        el = copy.deepcopy(proto)
        p._p.append(el)
        r = Run(el, p)
        r.text = thai_breaks(text)
        r.font.subscript = True if sty.get('sub') else None


def main(path):
    d = docx.Document(path)
    z = lambda s: s.replace('​', '')
    done = 0
    for key, parts in NEW:
        hits = [p for p in d.paragraphs if z(p.text).startswith(key)]
        if len(hits) != 1:
            raise SystemExit(f'expected one paragraph starting {key!r}, found {len(hits)}')
        set_runs(hits[0], parts)
        done += 1
    d.save(path)
    print(f'rewrote {done} paragraphs')


if __name__ == '__main__':
    main(sys.argv[1])
