def body(*parts, first=0.5):
    return para(doc, *parts, first=first)


def item(text):  # "1) ..." headings inside a subsection
    para(doc, text, align='left', first=0, left=0.75, keep_next=True)


def item_body(*parts):
    return para(doc, *parts, first=1.25)


def dots(items):
    for it in items:
        parts = it if isinstance(it, list) else [it]
        para(doc, '•\t', *parts, left=1.5, hanging=0.25, tabs=[(Inches(1.5).cm, 'l')])


def pborder(p, val):
    pPr = p._p.get_or_add_pPr()
    b = OxmlElement('w:pBdr'); bt = OxmlElement('w:bottom')
    bt.set(qn('w:val'), val); bt.set(qn('w:sz'), '12'); bt.set(qn('w:space'), '1'); bt.set(qn('w:color'), '000000')
    b.append(bt)
    pPr.insert_element_before(b, 'w:shd', 'w:tabs', 'w:suppressAutoHyphens', 'w:kinsoku', 'w:wordWrap',
                              'w:overflowPunct', 'w:topLinePunct', 'w:autoSpaceDE', 'w:autoSpaceDN', 'w:bidi',
                              'w:adjustRightInd', 'w:snapToGrid', 'w:spacing', 'w:ind', 'w:contextualSpacing',
                              'w:mirrorIndents', 'w:suppressOverlap', 'w:jc')


def tiny(p, pts=6):
    pf = p.paragraph_format
    pf.line_spacing = Pt(pts); pf.space_before = Pt(0); pf.space_after = Pt(0); pf.first_line_indent = Inches(0)
    r = p.add_run(''); _fonts(r._element.get_or_add_rPr(), size=4)


def zero_margins(cell):
    tcPr = cell._tc.get_or_add_tcPr(); mar = OxmlElement('w:tcMar')
    for side in ('left', 'right'):
        e = OxmlElement(f'w:{side}'); e.set(qn('w:w'), '0'); e.set(qn('w:type'), 'dxa'); mar.append(e)
    tcPr.append(mar)


def gantt():
    months = ['ก.ค', 'ส.ค', 'ก.ย', 'ต.ค', 'พ.ย']
    acts = [  # (name, start month index as float, end month index exclusive)
        ('1.ศึกษาข้อมูลและทฤษฎีที่เกี่ยวข้อง', 0.0, 2), ('2.กำหนดแนวคิดและขอบเขต', 0.0, 2),
        ('3.การออกแบบโครงสร้างทางกล', 0.18, 2), ('4.การออกแบบระบบไฟฟ้าและอิเล็กทรอนิกส์', 0.46, 2),
        ('5.การประกอบโครงสร้างหุ่นยนต์และติดตั้งระบบ', 0.0, 3), ('6.พัฒนาและเขียนโปรแกรมควบคุม', 2, 4),
        ('7.ทดลองและทดสอบการทำงานพร้อมบันทึกผล', 3, 5), ('8.การวิเคราะห์และอภิปราย', 3, 5),
        ('9.สรุปผลการดำเนินงาน', 4, 5), ('10.การจัดทำรูปเล่ม', 0, 5)]
    cap = para(doc, ('ตารางที่ 3.1', {'bold': True}), ' แผนการดำเนินงานของโครงการ', align='left', first=0, keep_next=True)
    cap.paragraph_format.space_before = Pt(6); cap.paragraph_format.space_after = Pt(3)
    MW = 1.5
    widths = [7.15] + [MW] * 5
    t = doc.add_table(rows=2 + len(acts), cols=6); t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    lay = OxmlElement('w:tblLayout'); lay.set(qn('w:type'), 'fixed'); t._tbl.tblPr.append(lay)
    for row in t.rows:
        for c, w in zip(row.cells, widths):
            c.width = Cm(w)
    add_runs(t.cell(0, 1).paragraphs[0], ['ปีการศึกษา 1/2569'])
    add_runs(t.cell(0, 0).paragraphs[0], ['กิจกรรม'])
    for k, m in enumerate(months):
        add_runs(t.cell(1, k + 1).paragraphs[0], [m])
    for (r, c) in [(0, 0), (0, 1)] + [(1, k) for k in range(1, 6)]:
        t.cell(r, c).paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        t.cell(r, c).vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    mg = t.cell(0, 1).merge(t.cell(0, 5))
    for p in mg.paragraphs[1:]:
        p._p.getparent().remove(p._p)
    mg = t.cell(0, 0).merge(t.cell(1, 0))
    for p in mg.paragraphs[1:]:
        p._p.getparent().remove(p._p)
    for i, (name, s, e) in enumerate(acts):
        r = i + 2
        c0 = t.cell(r, 0); add_runs(c0.paragraphs[0], [name]); c0.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        for m in range(5):
            cell = t.cell(r, m + 1); zero_margins(cell)
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            p1 = cell.paragraphs[0]; tiny(p1)
            if m + 1 > s and m < e:
                frac = max(0.0, s - m)
                p2 = cell.add_paragraph(); tiny(p2)
                for p in (p1, p2):
                    p.paragraph_format.left_indent = Cm(MW * frac)
                pborder(p1, 'dashed'); pborder(p2, 'single')
                p3 = cell.add_paragraph(); tiny(p3, 4)
    # legend
    leg = doc.add_table(rows=2, cols=2); leg.autofit = False
    for row, (val, txt) in zip(leg.rows, [('dashed', 'แสดงแผนการดำเนินงาน'), ('single', 'แสดงการดำเนินงานจริง')]):
        a, b = row.cells; a.width = Cm(2.2); b.width = Cm(8)
        a.vertical_alignment = b.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        pa = a.paragraphs[0]; tiny(pa, 8); pborder(pa, val)
        add_runs(b.paragraphs[0], [txt])
    para(doc, '', first=0)


